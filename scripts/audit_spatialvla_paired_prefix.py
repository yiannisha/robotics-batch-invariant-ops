"""Independent fail-closed audit for SpatialVLA SimplerEnv rollout evidence."""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import math
from collections import Counter
from pathlib import Path


CONDITIONS = {
    "native_singleton": (1, False),
    "native_dynamic": (4, False),
    "patched_singleton": (1, True),
    "patched_dynamic": (4, True),
}
PINNED = {
    "task_manifest_sha256": "a1f2b0895dd98b381668160c0c3a91b9c8f87a25f716e679f86fc802162bdc7c",
    "server_source_sha256": "8737b69fecb874d9363b7634972fe9a9b27bbe3dfde7d0bdf0061d55eca97018",
}
ALLOWED_CLIENT_SOURCE_SHA256 = {
    # Original probe/prefix client, valid for the WidowX-only evidence it produced.
    "8b702250904a568069b35b2b9b2f6ac1cc13a26d3eb0c5774b3c69aa07b2f359",
    # Full-suite client: adds the Google robot's agent.base_pose state schema.
    "71e2a321025eaaaaf8295bbbe3a2cb30bceea8f071a8a9781c274bab6362d9ff",
}
TASK_MANIFEST = Path(
    "/workspace/robotics-batch-invariant-ops/results/cross_model/spatialvla/"
    "full/closed_loop/paired/evaluator_task_manifest.json"
)
SEED = 20261005
MAX_STEPS = (60, 60, 60, 120, 113, 113, 113, 113, 113, 113, 80, 80)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def read_json(path: Path) -> dict:
    if path.suffix == ".gz":
        with gzip.open(path, "rt") as stream:
            return json.load(stream)
    return json.loads(path.read_text())


def valid_hash(value: object) -> bool:
    return isinstance(value, str) and len(value) == 64 and all(
        character in "0123456789abcdef" for character in value
    )


def finite_vector(value: object, *, nonempty: bool = True) -> bool:
    return (
        isinstance(value, list)
        and (bool(value) or not nonempty)
        and all(
            isinstance(number, (int, float))
            and not isinstance(number, bool)
            and math.isfinite(number)
            for number in value
        )
    )


def finite_matrix(value: object, rows: int, columns: int) -> bool:
    return (
        isinstance(value, list)
        and len(value) == rows
        and all(isinstance(row, list) and len(row) == columns and finite_vector(row) for row in value)
    )


def valid_state(value: object, expected_pose_key: str) -> bool:
    return (
        isinstance(value, dict)
        and expected_pose_key in {"tcp_pose", "base_pose"}
        and set(value) == {"qpos", "qvel", expected_pose_key}
        and finite_vector(value["qpos"])
        and finite_vector(value["qvel"])
        and len(value["qpos"]) == len(value["qvel"])
        and finite_vector(value[expected_pose_key])
    )


def infer_initialization_limit(tasks: list[dict], task_count: int, planned: int) -> int:
    candidates = [
        limit
        for limit in range(1, 51)
        if sum(min(task["initializations"], limit) for task in tasks[:task_count]) == planned
    ]
    if not candidates:
        raise ValueError("SpatialVLA planned cardinality is not generated by a pinned prefix limit")
    return max(candidates)


def audit(root: Path) -> dict:
    if not TASK_MANIFEST.is_file() or sha256(TASK_MANIFEST) != PINNED["task_manifest_sha256"]:
        raise ValueError("SpatialVLA pinned task manifest is missing or changed")
    task_manifest = json.loads(TASK_MANIFEST.read_text())
    tasks = task_manifest.get("tasks")
    if (
        task_manifest.get("schema_version") != 1
        or task_manifest.get("task_suite") != "simplerenv_spatialvla_semantic_12_variant"
        or task_manifest.get("task_count") != 12
        or task_manifest.get("initializations_per_condition") != 496
        or task_manifest.get("repository_revision") != "ccfe3809766839a2fcfb7a3d3c9abff585189188"
        or task_manifest.get("simulator_revision") != "cd45dd27dc6bb26d048cb6570cdab4e3f935cc37"
        or not isinstance(tasks, list)
        or len(tasks) != 12
        or [task.get("task_id") for task in tasks] != list(range(12))
    ):
        raise ValueError("SpatialVLA evaluator task manifest differs from the pinned suite")

    manifest = json.loads((root / "condition_manifest.json").read_text())
    condition = manifest.get("condition")
    if condition not in CONDITIONS:
        raise ValueError("unknown SpatialVLA condition")
    batch_size, repaired = CONDITIONS[condition]
    task_count = manifest.get("task_count")
    planned = manifest.get("planned_initializations")
    if (
        not isinstance(task_count, int)
        or not 1 <= task_count <= 12
        or not isinstance(planned, int)
        or planned <= 0
    ):
        raise ValueError("invalid SpatialVLA probe/full cardinality")
    initialization_limit = infer_initialization_limit(tasks, task_count, planned)
    required = {
        "schema_version": 1,
        "model": "spatialvla",
        "condition": condition,
        "batch_size": batch_size,
        "invariant_ops": repaired,
        "seed": SEED,
        "task_suite": "simplerenv_spatialvla_semantic_12_variant",
        "task_manifest_path": str(TASK_MANIFEST),
        "deterministic_policy": True,
        "explicit_physical_configuration": True,
        "websocket_ping_timeout_s": 600,
        **PINNED,
    }
    if (
        any(manifest.get(key) != value for key, value in required.items())
        or manifest.get("client_source_sha256") not in ALLOWED_CLIENT_SOURCE_SHA256
    ):
        raise ValueError("SpatialVLA manifest differs from pinned evaluator contract")

    metadata_path = root / "server_metadata.json"
    metadata = json.loads(metadata_path.read_text())
    if manifest.get("server_metadata_path") != str(metadata_path.resolve()):
        raise ValueError("SpatialVLA condition manifest points to another server record")
    if manifest.get("server_metadata_sha256") != sha256(metadata_path):
        raise ValueError("SpatialVLA live server record changed after condition freeze")
    expected_metadata = {
        "protocol_version": "2.1",
        "policy_type": "spatialvla",
        "checkpoint": "/workspace/assets/spatialvla/checkpoint",
        "task_suite": "simplerenv_spatialvla_semantic_12_variant",
        "paired_condition": condition,
        "genuine_batched_policy_call": True,
        "maximum_request_batch": batch_size,
        "batch_invariant_ops": repaired,
        "deterministic_policy": True,
        "unnorm_keys": {
            "google_robot": "fractal20220817_data/0.1.0",
            "widowx_bridge": "bridge_orig/1.0.0",
        },
        "image_size": [224, 224],
        "action_chunk_size": 4,
        "action_dim": 7,
        "action_ensemble_temperature": -0.8,
        "sticky_gripper_repeat": 10,
    }
    if any(metadata.get(key) != value for key, value in expected_metadata.items()):
        raise ValueError("SpatialVLA live server metadata differs from the requested condition")
    artifacts = metadata.get("artifact_files")
    if (
        not isinstance(artifacts, list)
        or len(artifacts) != 13
        or any(not isinstance(item, dict) or not valid_hash(item.get("sha256")) for item in artifacts)
        or not any(
            item.get("path") == "/workspace/assets/spatialvla/checkpoint/model.safetensors.index.json"
            and item.get("sha256") == "6c351156136b2452db86d3a426ff30adc9d11363b43f46fa69fe79d76b6d5c79"
            for item in artifacts
        )
    ):
        raise ValueError("SpatialVLA live server lacks the pinned checkpoint artifact set")

    expected_counts = {
        task["task_id"]: min(task["initializations"], initialization_limit)
        for task in tasks[:task_count]
    }
    counts, successes = Counter(), Counter()
    seen: set[tuple[int, int]] = set()
    files = sorted((root / "rollouts").glob("*.json"))
    files += sorted((root / "rollouts").glob("*.json.gz"))
    for path in files:
        payload = read_json(path)
        task = payload.get("task_id")
        ids = payload.get("explicit_initialization_ids")
        rows = payload.get("episodes")
        if (
            task not in range(task_count)
            or payload.get("task_name") != tasks[task]["name"]
            or not isinstance(ids, list)
            or not ids
            or len(ids) > batch_size
            or ids != list(range(ids[0], ids[0] + len(ids)))
            or any(index not in range(expected_counts[task]) for index in ids)
            or payload.get("seeds") != [SEED + index for index in ids]
            or not isinstance(rows, list)
            or len(rows) != len(ids)
        ):
            raise ValueError(f"invalid SpatialVLA physical rollout group: {path}")
        if batch_size == 1 and len(ids) != 1:
            raise ValueError(f"singleton SpatialVLA rollout is physically batched: {path}")
        for row, initialization in zip(rows, ids):
            key = (task, initialization)
            if key in seen:
                raise ValueError(f"duplicate SpatialVLA task/configuration: {key}")
            seen.add(key)
            states = row.get("trajectory")
            actions = row.get("action_sequence")
            selected = row.get("raw_action_sequence")
            chunks = row.get("raw_action_chunks")
            rewards = row.get("rewards")
            terminated = row.get("terminated")
            truncated = row.get("truncated")
            physical_batches = row.get("policy_batch_sizes")
            success = row.get("success")
            steps = len(actions) if isinstance(actions, list) else -1
            if (
                row.get("task") != task
                or row.get("task_name") != tasks[task]["name"]
                or row.get("task_group") != "simplerenv_spatialvla_semantic_12_variant"
                or not isinstance(row.get("task_description"), str)
                or not row["task_description"]
                or row.get("policy_setup") != tasks[task]["policy_setup"]
                or row.get("initialization_id") != initialization
                or row.get("reset_seed") != SEED + initialization
                or row.get("deterministic_policy") is not True
                or not valid_hash(row.get("initial_observation_sha256"))
                or not isinstance(success, bool)
                or not isinstance(states, list)
                or len(states) != steps + 1
                or steps <= 0
                or steps > MAX_STEPS[task]
                or any(
                    # The pinned SimplerEnv suite exposes an end-effector pose
                    # for the four Bridge tasks and the two Google manipulation
                    # tasks.  Only the six Google drawer environments expose the
                    # mobile-base pose recorded by the official client.
                    not valid_state(
                        state,
                        "base_pose" if 4 <= task <= 9 else "tcp_pose",
                    )
                    for state in states
                )
                or any(not finite_vector(action) or len(action) != 7 for action in actions)
                or not isinstance(selected, list)
                or len(selected) != steps
                or any(not finite_vector(action) or len(action) != 7 for action in selected)
                or not isinstance(chunks, list)
                or len(chunks) != steps
                or any(not finite_matrix(chunk, 4, 7) for chunk in chunks)
                or not isinstance(rewards, list)
                or len(rewards) != steps
                or any(
                    not isinstance(reward, (int, float))
                    or isinstance(reward, bool)
                    or not math.isfinite(reward)
                    for reward in rewards
                )
                or not isinstance(terminated, list)
                or len(terminated) != steps
                or any(not isinstance(value, bool) for value in terminated)
                or not isinstance(truncated, list)
                or len(truncated) != steps
                or any(not isinstance(value, bool) for value in truncated)
                or success != any(terminated)
                or not isinstance(physical_batches, list)
                or len(physical_batches) != steps
                or physical_batches[0] != len(ids)
                or any(
                    not isinstance(size, int) or not 1 <= size <= len(ids)
                    for size in physical_batches
                )
            ):
                raise ValueError(f"incomplete or inconsistent SpatialVLA episode: {path}")
            counts[task] += 1
            successes[task] += int(success)

    for task in range(task_count):
        observed = {
            initialization
            for observed_task, initialization in seen
            if observed_task == task
        }
        if observed != set(range(len(observed))):
            raise ValueError(f"noncontiguous SpatialVLA configuration prefix for task {task}")
        if counts[task] and any(
            counts[previous] != expected_counts[previous] for previous in range(task)
        ):
            raise ValueError(f"SpatialVLA task {task} started before its predecessor completed")

    info_path = root / "official/eval_info.json"
    if info_path.is_file():
        info = json.loads(info_path.read_text())
        overall = info.get("overall", {})
        if (
            info.get("schema_version") != 1
            or info.get("condition") != condition
            or info.get("task_suite") != "simplerenv_spatialvla_semantic_12_variant"
            or overall.get("n_episodes") != sum(counts.values())
            or overall.get("n_success") != sum(successes.values())
        ):
            raise ValueError("SpatialVLA raw episodes and aggregate metrics differ")
    return {
        "schema_version": 1,
        "evidence_tier": (
            "checkpoint_matched_probe"
            if planned < 496
            else "running_prefix_only_not_paired_completion"
        ),
        "model_id": "spatialvla",
        "condition": condition,
        "task_count": task_count,
        "initialization_limit": initialization_limit,
        "episodes_cached": sum(counts.values()),
        "successes_cached": sum(successes.values()),
        "planned_episodes": planned,
        "complete": sum(counts.values()) == planned,
        "integrity_passed": True,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--condition-root", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(audit(args.condition_root), sort_keys=True))


if __name__ == "__main__":
    main()
